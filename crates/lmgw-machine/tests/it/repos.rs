//! Repository sections after dnf5's overrides, and the metadata cache times
//! (machine-check design §3.2, "Which sections count").

use lmgw_machine::fake::FakeFacts;
use lmgw_machine::repos::{
    cache_dir_id, cache_times, glob_match, parse_ini, primary_location, read_repos, DNF_CACHE,
};

const NVIDIA_REPO: &str = "\
[nvidia-container-toolkit]
name=nvidia-container-toolkit
baseurl=https://nvidia.github.io/libnvidia-container/stable/rpm/$basearch
repo_gpgcheck=1
gpgcheck=0
enabled=1
gpgkey=https://nvidia.github.io/libnvidia-container/gpgkey

[nvidia-container-toolkit-experimental]
name=nvidia-container-toolkit-experimental
baseurl=https://nvidia.github.io/libnvidia-container/experimental/rpm/$basearch
repo_gpgcheck=1
gpgcheck=0
enabled=0
gpgkey=https://nvidia.github.io/libnvidia-container/gpgkey
";

const DRIVER_REPO: &str = "\
[rpmfusion-nonfree-nvidia-driver]
name=RPM Fusion for Fedora $releasever - Nonfree - NVIDIA Driver
metalink=https://mirrors.rpmfusion.org/metalink?repo=nonfree-fedora-nvidia-driver-$releasever&arch=$basearch
enabled=0
type=rpm-md
";

/// dnf5 config-manager's own override file, as it writes it.
const CONFIG_MANAGER: &str = "\
# Generated by dnf5 config-manager.
# Do not modify this file manually, use dnf5 config-manager instead.
[rpmfusion-nonfree-nvidia-driver]
enabled=1
[nvidia-container-toolkit]
enabled=0
";

#[test]
fn an_override_switches_a_section_on_that_its_file_switches_off_and_the_reverse() {
    let f = FakeFacts::new();
    f.file(
        "/etc/yum.repos.d/nvidia-container-toolkit.repo",
        NVIDIA_REPO,
    )
    .file(
        "/etc/yum.repos.d/rpmfusion-nonfree-nvidia-driver.repo",
        DRIVER_REPO,
    )
    .file(
        "/etc/dnf/repos.override.d/99-config_manager.repo",
        CONFIG_MANAGER,
    );
    let repos = read_repos(&f);

    let driver = repos.get("rpmfusion-nonfree-nvidia-driver").unwrap();
    assert!(!driver.enabled_in_file);
    assert!(driver.enabled, "the override switches it on");
    assert_eq!(driver.overridden_by.len(), 1);

    let nvidia = repos.get("nvidia-container-toolkit").unwrap();
    assert!(nvidia.enabled_in_file);
    assert!(!nvidia.enabled, "and this one off");
    assert_eq!(
        nvidia.baseurl,
        vec!["https://nvidia.github.io/libnvidia-container/stable/rpm/$basearch".to_string()]
    );
    assert_eq!(nvidia.gpgcheck, Some(false));
    assert_eq!(nvidia.repo_gpgcheck, Some(true));

    let exp = repos.get("nvidia-container-toolkit-experimental").unwrap();
    assert!(!exp.enabled && exp.overridden_by.is_empty());
}

#[test]
fn the_administrators_override_comes_after_the_distributions() {
    let f = FakeFacts::new();
    f.file(
        "/etc/yum.repos.d/nvidia-container-toolkit.repo",
        NVIDIA_REPO,
    )
    .file(
        "/usr/share/dnf5/repos.override.d/50-distro.repo",
        "[nvidia-*]\nenabled=0\n",
    )
    .file(
        "/etc/dnf/repos.override.d/10-admin.repo",
        "[nvidia-container-toolkit]\nenabled=1\nincludepkgs=nvidia-container-toolkit-base\n",
    );
    let repos = read_repos(&f);
    let nvidia = repos.get("nvidia-container-toolkit").unwrap();
    assert!(nvidia.enabled, "the /etc override wins over /usr/share");
    assert_eq!(nvidia.includepkgs, vec!["nvidia-container-toolkit-base"]);
    assert_eq!(nvidia.overridden_by.len(), 2);
    let exp = repos.get("nvidia-container-toolkit-experimental").unwrap();
    assert!(
        !exp.enabled,
        "the glob reached it, the later override did not"
    );
}

#[test]
fn an_unreadable_repo_file_is_skipped_and_named() {
    let f = FakeFacts::new();
    f.file_mode(
        "/etc/yum.repos.d/private.repo",
        "[private]\nbaseurl=https://example.com/\n",
        0o600,
    )
    .file("/etc/yum.repos.d/notes.txt", "[not-a-repo]\n");
    let repos = read_repos(&f);
    assert!(repos.sections.is_empty(), "{:?}", repos.sections);
    assert_eq!(repos.skipped.len(), 1);
    assert!(repos.skipped[0].path.ends_with("private.repo"));
}

#[test]
fn every_dnf5_repo_dir_is_read_and_the_first_section_of_an_id_wins() {
    let f = FakeFacts::new();
    f.file(
        "/usr/share/dnf5/repos.d/vendor.repo",
        "[vendor]\nenabled=0\n",
    )
    .file("/etc/yum.repos.d/a.repo", "[vendor]\nenabled=1\n");
    let repos = read_repos(&f);
    assert_eq!(repos.sections.len(), 1);
    assert!(repos.get("vendor").unwrap().enabled);
    assert!(repos.get("vendor").unwrap().file.ends_with("a.repo"));
}

#[test]
fn ini_values_continue_on_indented_lines() {
    let ini = parse_ini(
        "; a comment\n[s]\nbaseurl=https://a.example/\n  https://b.example/\nincludepkgs = a, b\n",
    );
    assert_eq!(ini[0].header, "s");
    assert_eq!(
        ini[0].entries,
        vec![
            (
                "baseurl".to_string(),
                "https://a.example/ https://b.example/".to_string()
            ),
            ("includepkgs".to_string(), "a, b".to_string()),
        ]
    );
}

#[test]
fn globs_match_like_fnmatch() {
    assert!(glob_match("*", "anything"));
    assert!(glob_match("nvidia-*", "nvidia-container-toolkit"));
    assert!(glob_match(
        "copr:*:example",
        "copr:copr.fedorainfracloud.org:another:example"
    ));
    assert!(glob_match("updates?", "updates2"));
    assert!(!glob_match("nvidia-*", "rpmfusion-nvidia"));
}

/// `repomd.xml` naming its primary metadata file, as createrepo_c writes
/// it (the layout of NVIDIA's repository, the checksum shortened).
fn repomd(primary: &str) -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<repomd xmlns=\"http://linux.duke.edu/metadata/repo\">\n  \
         <revision>1.0</revision>\n  <data type=\"primary\">\n    <checksum type=\"sha512\">3864</checksum>\n    \
         <location href=\"repodata/{primary}\"/>\n    <timestamp>1789765756</timestamp>\n  </data>\n  \
         <data type=\"filelists\">\n    <location href=\"repodata/cf97-filelists.xml.gz\"/>\n  </data>\n</repomd>\n"
    )
}

/// A cache dir of `id` whose `repomd.xml` was stored at `repomd_ns` and
/// whose primary file dnf last loaded at `primary_ns`.
fn cache(f: &FakeFacts, dir: &str, repomd_ns: i128, primary_ns: i128) {
    let primary = "3864-primary.xml.gz";
    f.file(format!("{dir}/repodata/repomd.xml"), repomd(primary))
        .touch(format!("{dir}/repodata/repomd.xml"), repomd_ns)
        .file(format!("{dir}/repodata/{primary}"), b"")
        .touch(format!("{dir}/repodata/{primary}"), primary_ns);
}

/// dnf5's clock is the primary metadata file's mtime (`Repo::get_age`), which
/// it sets to now when expired metadata is still in sync: the time read, not
/// `repomd.xml`'s (when the source published) or the dir's.
#[test]
fn cache_times_are_the_primary_files_and_each_sections_newest_dir() {
    let f = FakeFacts::new();
    let old =
        format!("{DNF_CACHE}/copr:copr.fedorainfracloud.org:someone:example-0123456789abcdef");
    let new =
        format!("{DNF_CACHE}/copr:copr.fedorainfracloud.org:someone:example-fedcba9876543210");
    let fedora = format!("{DNF_CACHE}/fedora-1123456789abcdef");
    cache(&f, &old, 10, 10);
    cache(&f, &new, 20, 25);
    // Fedora's release-day repomd.xml, its primary file confirmed since.
    cache(&f, &fedora, 30, 90);
    f.touch(&fedora, 500)
        .file(format!("{DNF_CACHE}/temporary_files.toml"), b"")
        .dir(format!("{DNF_CACHE}/@commandline-0123456789abcdef"));
    // A dir whose repomd.xml names no primary file dnf could load.
    let broken = format!("{DNF_CACHE}/broken-0123456789abcdef");
    f.file(
        format!("{broken}/repodata/repomd.xml"),
        repomd("gone-primary.xml.gz"),
    );
    let times = cache_times(&f);
    assert_eq!(times.len(), 2, "{times:?}");
    let example = times
        .iter()
        .find(|t| t.id == "copr:copr.fedorainfracloud.org:someone:example")
        .unwrap();
    assert_eq!((example.repomd_mtime_ns, example.checked_ns), (20, 25));
    assert!(example.primary.ends_with("repodata/3864-primary.xml.gz"));
    let fedora = times.iter().find(|t| t.id == "fedora").unwrap();
    assert_eq!(
        (fedora.repomd_mtime_ns, fedora.checked_ns),
        (30, 90),
        "the primary file's time, never the dir's"
    );
    assert_eq!(cache_dir_id("updates-2123456789abcdef"), Some("updates"));
    assert_eq!(cache_dir_id("temporary_files.toml"), None);
}

#[test]
fn the_primary_location_stays_inside_the_cache_dir() {
    assert_eq!(
        primary_location(&repomd("3864-primary.xml.gz")),
        Some("repodata/3864-primary.xml.gz")
    );
    let single =
        "<repomd><data type='primary'><location href='repodata/p.xml.zck'/></data></repomd>";
    assert_eq!(primary_location(single), Some("repodata/p.xml.zck"));
    for bad in ["/etc/shadow", "../../etc/passwd", "repodata/../../x", ""] {
        let text = format!("<data type=\"primary\"><location href=\"{bad}\"/></data>");
        assert_eq!(primary_location(&text), None, "{bad}");
    }
    assert_eq!(
        primary_location("<data type=\"filelists\"><location href=\"f\"/></data>"),
        None
    );
}

/// An override file root could read and the user cannot is read by neither,
/// and named: otherwise root's `enabled` would differ from the user's and
/// every plan root recomputes would differ from the one shown.
#[test]
fn an_override_file_not_readable_by_every_user_is_skipped_and_named() {
    let f = FakeFacts::new();
    f.file(
        "/etc/yum.repos.d/nvidia-container-toolkit.repo",
        NVIDIA_REPO,
    )
    .file_mode(
        "/etc/dnf/repos.override.d/99-config_manager.repo",
        CONFIG_MANAGER,
        0o600,
    );
    let repos = read_repos(&f);
    let nvidia = repos.get("nvidia-container-toolkit").unwrap();
    assert!(nvidia.enabled, "the unreadable override was not applied");
    assert!(nvidia.overridden_by.is_empty());
    assert_eq!(repos.skipped.len(), 1, "{:?}", repos.skipped);
    assert!(repos.skipped[0].path.ends_with("99-config_manager.repo"));
    assert_eq!(repos.skipped[0].why, "not readable by every user");
}
